"""AI field inspection assistant page (retrieval over local guidelines + Ollama)."""

from __future__ import annotations

import streamlit as st

from app.common import get_repository, reference_caption, results
from src.config.settings import ollama_settings
from src.rag_assistant.answer import answer_question
from src.rag_assistant.index import Retriever, index_status

repo = get_repository()
data = results(repo)
villages = repo.villages()
crops = repo.crops()


@st.cache_resource(show_spinner="Loading guideline index…")
def get_retriever() -> Retriever:
    """Build the retriever once per app process."""
    return Retriever()


st.title("AI field inspection assistant")
reference_caption(data["reference_date"])

retriever = get_retriever()
status = index_status()
base_url, model = ollama_settings()

col_a, col_b, col_c = st.columns(3)
col_a.metric("Retrieval mode", status["mode"])
col_b.metric("Indexed chunks", status["chunks"])
col_c.metric("LLM", model if status["mode"] != "none" else "—")

st.caption(
    f"Ollama endpoint: {base_url} · embedding: {status['embedding_model']} · "
    "answers are restricted to retrieved passages and always cite document + page."
)
if status["mode"] == "tfidf":
    st.info(
        "Running the TF-IDF fallback: `sentence-transformers` and `faiss-cpu` are not "
        "installed, so semantic similarity is approximated by keyword similarity.",
        icon="ℹ️",
    )

with st.sidebar:
    st.subheader("Context (optional)")
    village = st.selectbox("Village", ["—"] + villages["village_name"].tolist(), key="rag_village")
    crop = st.selectbox("Crop", ["—"] + crops["crop_name"].tolist(), key="rag_crop")
    category = st.selectbox(
        "Issue category",
        ["—", "pest_attack", "disease_outbreak", "drought_stress", "flood_damage", "nutrient_deficiency", "irrigation_issue"],
        key="rag_category",
    )

context = {
    "village": "" if village == "—" else village,
    "crop": "" if crop == "—" else crop,
    "issue": "" if category == "—" else category,
}

question = st.text_input(
    "Ask about inspection, symptoms or guidelines",
    value="What should I check first in a paddy field with planthopper hoppers?",
)
if st.button("Ask", type="primary"):
    if not question.strip():
        st.warning("Enter a question first.")
    else:
        with st.spinner("Retrieving guidelines and asking the local model…"):
            result = answer_question(question, context=context, retriever=retriever)
        st.markdown(result["answer"])
        st.caption(f"Answer mode: {result['mode']}")
        if result["sources"]:
            st.subheader("Sources")
            for source in result["sources"]:
                with st.expander(f"{source['citation']} {source['document']} · page {source['page']} (score {source['score']})"):
                    st.write(source["excerpt"])
        else:
            st.warning("Nothing relevant was retrieved, so no answer was generated.", icon="🚫")

st.divider()
with st.expander("About this assistant (honest limits)"):
    st.write(
        """
- Retrieval is limited to the documents in `guidelines_pdfs/`. Official ICAR/UAS PDFs are
  not committed (licence/size); run `python -m src.ingestion.download_guidelines` and place
  the PDFs there, then rebuild the index.
- The committed corpus contains one clearly-labelled **internal demo note**, not an
  official government document.
- Answers are generated by the local Ollama model from retrieved passages only, and the
  assistant refuses when retrieval is empty. It is a decision *aid*, not a prescription:
  the officer verifies in the field.
        """
    )
